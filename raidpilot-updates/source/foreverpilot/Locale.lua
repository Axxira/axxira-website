-- Only addon-owned interface text is translated. Game data and identifiers are not.
local B = ForeverPilotLeveling
B.language = "frFR"
B.locales = {}
local labelTables = {}
local aliases = {en="enUS",enus="enUS",engb="enUS",fr="frFR",frfr="frFR",de="deDE",dede="deDE",
    es="esES",eses="esES",esmx="esMX",it="itIT",itit="itIT",pt="ptBR",ptbr="ptBR",ru="ruRU",ruru="ruRU",
    ko="koKR",kokr="koKR",zhcn="zhCN",zhtw="zhTW"}
local choices = {{"enUS","English"},{"frFR","Français"},{"deDE","Deutsch"},{"esES","Español (ES)"},
    {"esMX","Español (MX)"},{"itIT","Italiano"},{"ptBR","Português (BR)"},{"ruRU","Русский"},
    {"koKR","한국어"},{"zhCN","简体中文"},{"zhTW","繁體中文"}}
local foreignLabels={ruRU="Russian",koKR="Korean",zhCN="Chinese (CN)",zhTW="Chinese (TW)"}
local function languageName(entry)
    -- European clients may not contain glyphs for every language in the menu.
    return B.NormalizeLocale(B.Call(GetLocale))~=entry[1] and foreignLabels[entry[1]] or entry[2]
end

function B.NormalizeLocale(code)
    return type(code) == "string" and aliases[code:lower()] or nil
end
function B.RegisterLocale(code, values)
    local canonical = B.NormalizeLocale(code)
    if not canonical or type(values) ~= "table" then return false end
    B.locales[canonical] = values
    return true
end
function B.T(text)
    local locale = B.locales[B.language] or {}
    local english = B.locales.enUS or {}
    return locale[text] or english[text] or text
end
function B.LanguageChoices()
    local result = {{"auto", B.T("Auto · langue du jeu")}}
    for _, entry in ipairs(choices) do result[#result + 1] = {entry[1], languageName(entry)} end
    return result
end
function B.LanguageLabel(code)
    if code == "auto" then return B.T("Auto · langue du jeu") end
    code = B.NormalizeLocale(code)
    for _, entry in ipairs(choices) do if entry[1] == code then return languageName(entry) end end
    return "English"
end

-- Flat display labels only. Nested structures must register explicit display fields;
-- no recursion into profile/race tokens, route keys, item links or game data.
function B.LocalizeLabels(labels, fields)
    local source = {}
    if type(fields) == "table" then
        for _, key in ipairs(fields) do if type(labels[key]) == "string" then source[key] = labels[key] end end
    else
        for key, value in pairs(labels) do if type(value) == "string" then source[key] = value end end
    end
    labelTables[#labelTables + 1] = {target=labels, source=source}
end
function B.InitLocale()
    local saved = type(ForeverPilotLevelingDB) == "table" and ForeverPilotLevelingDB.brain
    local selected = type(saved) == "table" and saved.language or nil
    if selected == nil and type(saved) == "table" then selected = "frFR" end -- preserve pre-language installs
    if selected == "auto" or selected == nil then
        B.language = B.NormalizeLocale(B.Call(GetLocale)) or "enUS"
    else
        B.language = B.NormalizeLocale(selected) or "enUS"
    end
    if type(saved) == "table" and selected ~= "auto" then saved.language = B.language end
    for _, entry in ipairs(labelTables) do
        for key, value in pairs(entry.source) do entry.target[key] = B.T(value) end
    end
end
function B.SetLanguage(language)
    local selected = language == "auto" and "auto" or B.NormalizeLocale(language)
    if not selected or not B.settings then return false end
    B.settings.language = selected
    if B.Call(InCombatLockdown) == true or type(ReloadUI) ~= "function" then
        B.Print(B.T("Langue enregistrée. Tape /reload hors combat pour l'appliquer."))
    else
        ReloadUI()
    end
    return true
end

